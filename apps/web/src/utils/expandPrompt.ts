/**
 * 查询扩展的 Prompt（纯函数，钉字节）。
 *
 * 为什么单独成文件：服务端（apps/api/app/parity/expand_prompt.py）要用**逐字节相同**的
 * Prompt —— 一端改一个字，双端评测就不再同口径（与 answerPrompt.ts 同一条纪律）。
 *
 * 任务定位：把**口语化提问**改写成**术语化检索词**。
 * 典型用例：用户问「这台东西在严寒酷暑下还能正常干活吗」，
 * 语料里的说法是「工作温度 -20℃~70℃」—— 两者零词重合，
 * BM25 与 IDF 覆盖率这类词表信号完全失效（这也是检索侧会误拒口语化提问的根因）。
 * 改写出来的术语化查询既能救回词表信号，也给向量路多一个问法。
 */

export interface ExpandPromptInput {
  question: string;
  /** 生成几条改写（默认 3，取 2~3 条最稳） */
  max?: number;
}

/**
 * 构造改写 Prompt。
 *
 * **为什么是"关键词"而不是"改写句子"**（0.5B 上的实测对比，2026-10-15）：
 * 让模型"改写成术语化的句子"时，它输出的是**冗长的同义复述**
 * （「这台东西在严寒酷暑下还能正常干活吗」→「设备在不同环境条件下的性能和可靠性分析」），
 * 仍然不含任何语料术语 —— 词表信号（IDF 覆盖率 / BM25 最高分）照样是 0，
 * 检索侧照样把这类问题粗拒。改成"只输出名词/术语，空格分隔"后，
 * 同一模型给出的关键词组开始命中语料词表：s 组最好一条的 IDF 覆盖率
 * 0.237 → 0.370、BM25 最高分 7.74 → 8.91（两条门限都跨过去了）。
 *
 * 一句话：**小模型做"抽取"比做"改写"可靠**。
 *
 * 三条规则各自堵一种失败模式：
 * 1. 只输出名词/术语 → 避免动词与疑问词稀释词表命中
 * 2. 不许添加原问题没有的信息 → 避免检索被带偏（扩展是增强项，不该引入新主题）
 * 3. 每行一组 + 最多 N 行 → 解析层能稳定切开（弱模型不守格式是常态）
 */
export function buildExpandPrompt(input: ExpandPromptInput): string {
  const max = input.max ?? 3;
  return `<|im_start|>system
你是检索助手。把用户问题改写成**技术文档里可能出现的检索关键词**。

规则：
1. 只输出名词或术语，不要成句、不要疑问词
2. 每行一组，词与词之间用空格分隔
3. 不要添加原问题里没有的信息
4. 最多 ${max} 行，每行最多 10 个词<|im_end|>
<|im_start|>user
${input.question}<|im_end|>
<|im_start|>assistant
`;
}
